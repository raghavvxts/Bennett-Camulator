CREATE TABLE IF NOT EXISTS accounts (id INTEGER PRIMARY KEY, sealed TEXT NOT NULL, linked_at TEXT NOT NULL, token_hash TEXT UNIQUE);
CREATE TABLE IF NOT EXISTS conversations (id INTEGER PRIMARY KEY, sealed TEXT NOT NULL, expires INTEGER NOT NULL);
CREATE TABLE IF NOT EXISTS operations (account TEXT PRIMARY KEY, uncertain INTEGER NOT NULL DEFAULT 0);
CREATE TABLE IF NOT EXISTS leases (key TEXT PRIMARY KEY, token TEXT NOT NULL, expires INTEGER NOT NULL);
CREATE TABLE IF NOT EXISTS updates (id INTEGER PRIMARY KEY, expires INTEGER NOT NULL);
CREATE TABLE IF NOT EXISTS owner_auth (id INTEGER PRIMARY KEY CHECK(id=1), failures INTEGER NOT NULL DEFAULT 0, window_start INTEGER NOT NULL DEFAULT 0, locked_until INTEGER NOT NULL DEFAULT 0);
